#!/usr/bin/env python3
"""Table 4 (`tab:benchmarks`) from the paper_bench runs of https://anonymous.4open.science/status/vpir-pdr (scripts/bench.sbatch).

Reads results/vpir/<job>.d10.jsonl, .d11.jsonl, .d12.jsonl (one JSON object per shape; medians over reps)
and prints the LaTeX rows: per corpus, the Round-1 and Round-2 shapes, client time, server time and price,
each at b=2 (Round 1 at d=2^10) and at b>=3 (Round 1 at d=2^11); Round 2 (d=2^12) is common to both.
Also prints the malicious-security premium (prove / matvec-only at the SciFact Round-1 shape) and the
communication volumes as the implementation sends them.

Usage: python analysis/cost_table.py [--job <job id>] [--rate 7.20]
"""
import argparse, glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--job", default=None, help="job id; default: latest present")
ap.add_argument("--rate", type=float, default=7.20, help="USD per hour for 48 cores (hpc7a.24xlarge on-demand)")
ap.add_argument("--results", default=os.path.join(HERE, "..", "results", "vpir"))
args = ap.parse_args()

files = sorted(glob.glob(os.path.join(args.results, "*.d1[012].jsonl")))
if args.job:
    files = [f for f in files if os.path.basename(f).startswith(args.job + ".")]
rows = {}
for f in files:
    for line in open(f):
        line = line.strip()
        if not line:
            continue
        r = json.loads(line)
        rows[(r["D"], r["t"], r["h"])] = r  # later jobs override earlier ones

# The retrieval unit is a 1,536-byte chunk (512 coefficients of 24 bits), so Round 2 has 512 rows and one
# block of the encrypted one-hot vector per 4,096 chunks; Round 1 has one padded row per chunk.
# corpus -> (label, A shape, D^T shape, padded rows of A = chunk count padded, Round-2 blocks t = padded chunks / 4096)
ELL = 512
CORPORA = [
    ("NFCorpus ($5{,}761$ chunks)", "$5{,}761 \\times 1{,}024$", "$512 \\times 5{,}761$", 8192, 2),
    ("SciFact ($7{,}510$ chunks)", "$7{,}510 \\times 1{,}024$", "$512 \\times 7{,}510$", 8192, 2),
    ("$m = 10^4$", "$10^4 \\times 1{,}024$", "$512 \\times 10^4$", 16384, 4),
    ("$m = 10^5$", "$10^5 \\times 1{,}024$", "$512 \\times 10^5$", 131072, 32),
    ("$m = 10^6$", "$10^6 \\times 1{,}024$", "$512 \\times 10^6$", 1048576, 256),
]

def fmt_s(x):
    if x < 1: return f"${x*1000:.0f}$\\,ms"
    if x < 60: return f"${x:.1f}$\\,s"
    return f"${x/60:.1f}$\\,min"

def client(r1, r2):
    return sum(r[k] for r in (r1, r2) for k in ("keygen_encrypt_s", "verify_s", "decrypt_s"))

def server(r1, r2):
    return r1["prove_s"] + r2["prove_s"]

print("% tab:benchmarks rows, generated by analysis/cost_table.py from", [os.path.basename(f) for f in files])
print("% Corpus & Round 1 & Round 2 & Client (b=2 / b>=3) & Server (b=2 / b>=3) & $/query (b=2 / b>=3)")
for name, a_shape, d_shape, h1, t2 in CORPORA:
    r10, r11, r12 = rows.get((1024, 1, h1)), rows.get((2048, 1, h1)), rows.get((4096, t2, ELL))
    if not (r10 and r11 and r12) and h1 == 1048576:
        # Any 10^6 shape not measured is projected from the 10^5 shape (work is linear in the padded matrix size).
        base = (rows.get((1024, 1, 131072)), rows.get((2048, 1, 131072)), rows.get((4096, 32, ELL)))
        scale = lambda r: {k: (v * 8 if isinstance(v, float) else v) for k, v in r.items()}
        proj = []
        if r10 is None and base[0]: r10 = scale(base[0]); proj.append("Round 1")
        if r11 is None and base[1]: r11 = scale(base[1]); proj.append("Round 1")
        if r12 is None and base[2]: r12 = scale(base[2]); proj.append("Round 2")
        if proj:
            name += " (" + " and ".join(sorted(set(proj))) + " projected)"
    if not (r10 and r11 and r12):
        print(f"% {name}: missing runs (d10={bool(r10)}, d11={bool(r11)}, d12={bool(r12)})")
        continue
    c2, c3 = client(r10, r12), client(r11, r12)
    s2, s3 = server(r10, r12), server(r11, r12)
    print(f"{name} & {a_shape} & {d_shape} & {fmt_s(c2)} / {fmt_s(c3)} & {fmt_s(s2)} / {fmt_s(s3)} & "
          f"${s2/3600*args.rate:.3f}$ / ${s3/3600*args.rate:.3f}$ \\\\")

r = rows.get((1024, 1, 8192))
if r:
    print(f"% malicious-security premium at 2^10 x 2^13, d=2^10: matvec {r['matvec_s']*1000:.1f} ms, "
          f"prove {r['prove_s']:.2f} s, factor {r['prove_s']/r['matvec_s']:.0f}x; proof {r['proof_bytes']/1024:.0f} KiB")
r = rows.get((2048, 1, 8192))
if r:
    print(f"% same at d=2^11: matvec {r['matvec_s']*1000:.1f} ms, prove {r['prove_s']:.2f} s, factor {r['prove_s']/r['matvec_s']:.0f}x")
import math
print("% communication per the paper's formula (packed responses): upload ceil(N/d)(kappa+1)d log q, download ceil(m'/d)(kappa+1)d log q + proof")
CORPUS_M = {"NFCorpus": (5761, ELL), "SciFact": (7510, ELL), "10^4": (10**4, ELL), "10^5": (10**5, ELL), "10^6": (10**6, ELL)}
for name, _, _, h1, t2 in CORPORA:
    key = next((k for k in CORPUS_M if k in name), None)
    if key is None: continue
    m, ell = CORPUS_M[key]
    for d1, lab in ((1024, "b=2"), (2048, "b>=3")):
        r1, r2 = rows.get((d1, 1, h1)), rows.get((4096, t2, ELL))
        p1 = r1["proof_bytes"] if r1 else 110 * 1024
        p2 = r2["proof_bytes"] if r2 else 120 * 1024
        up = math.ceil(1024 / d1) * 2 * d1 * 8 + math.ceil(m / 4096) * 2 * 4096 * 8
        down = math.ceil(m / d1) * 2 * d1 * 8 + p1 + math.ceil(ell / 4096) * 2 * 4096 * 8 + p2
        print(f"%   {key:9s} {lab:5s}: upload {up/1024:.0f} KiB, download {down/1024:.0f} KiB, total {(up+down)/1024:.0f} KiB"
              + ("" if r1 and r2 else " (proof sizes assumed)"))
print("% communication as sent by this implementation (one ring element per output row; NOT the paper's figures):")
for name, _, _, h1, t2 in CORPORA:
    for D, t, h, lab in ((1024, 1, h1, "R1 d=2^10"), (2048, 1, h1, "R1 d=2^11"), (4096, t2, ELL, "R2 d=2^12")):
        r = rows.get((D, t, h))
        if r:
            print(f"%   {name:28s} {lab}: up {r['upload_bytes']/1024:.0f} KiB, response {(r['response_bytes']+r['proof_bytes'])/2**20:.1f} MiB")
