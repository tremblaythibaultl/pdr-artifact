#!/usr/bin/env python3
"""Retrieval quality versus corpus size from results/scale/*.csv.

Writes figures/scale_sweep.tex (standalone pgfplots, data via filecontents):
left, top-1 agreement with the floating-point ranking at b=4 (solid) against
the lossless b=8 ceiling (dashed); right, nDCG@10 retained at b=4 (solid) and
b=3 (dashed). Compile with `pdflatex scale_sweep.tex` inside figures/.
"""
from __future__ import annotations

import csv
import pathlib
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "scale"
OUT = ROOT / "figures"
ENC = [
    ("arctic", "Snowflake_snowflake-arctic-embed-l-v2.0", "arctic-l-v2.0 (quant.-aware)", "red!80!black"),
    ("bge", "BAAI_bge-large-en-v1.5", "bge-large", "blue!70!black"),
    ("gte", "thenlper_gte-large", "gte-large", "violet"),
]
MARK = {"arctic": "*", "bge": "triangle*", "gte": "o"}


def main() -> None:
    data = {}
    for key, stem, *_ in ENC:
        d = defaultdict(dict)
        with (RES / f"scale__nq__{stem}__clip99.csv").open() as f:
            for r in csv.DictReader(f):
                d[int(r["m"])][r["bits"]] = r
        data[key] = d
    ms = sorted(next(iter(data.values())))
    lines = [
        "% top-1 agreement and nDCG@10 retained versus corpus size, BEIR-NQ, clipped p99.",
        "% GENERATED by figures/gen_scale.py from results/scale/scale__nq__<model>__clip99.csv.",
        r"\documentclass[border=3pt]{standalone}", r"\usepackage{pgfplots}", r"\pgfplotsset{compat=1.18}",
        r"\usepgfplotslibrary{groupplots}", "",
        r"\begin{filecontents*}[overwrite]{scale_data.csv}",
        "m," + ",".join(f"{k}_t4,{k}_t8,{k}_r4,{k}_r3" for k, *_ in ENC),
    ]
    for m in ms:
        cells = []
        for k, *_ in ENC:
            d = data[k][m]
            cells += [d["4"]["top1_agreement"], d["8"]["top1_agreement"], d["4"]["ndcg_retained_pct"], d["3"]["ndcg_retained_pct"]]
        lines.append(f"{m}," + ",".join(f"{float(c):.4f}" for c in cells))
    lines += [
        r"\end{filecontents*}", "", r"\begin{document}", r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        r"    group style={group size=2 by 1, horizontal sep=1.5cm},",
        r"    width=7.4cm, height=4.8cm, xmode=log, xmin=6000, xmax=4500000,",
        r"    xtick={10000,100000,1000000}, xticklabels={$10^4$,$10^5$,$10^6$},",
        r"    extra x ticks={2681468}, extra x tick labels={$2.7{\cdot}10^6$}, extra x tick style={tick label style={yshift=-0.35em}},",
        r"    xlabel={corpus size $m$}, tick label style={font=\small}, label style={font=\small}, title style={font=\small},",
        r"    grid=major, grid style={gray!20}, legend cell align=left,",
        r"    legend style={font=\footnotesize, draw=black!40, fill=white, rounded corners=1pt},",
        r"]",
        r"\nextgroupplot[title={exact top-1}, ylabel={top-1 agreement with float}, ymin=0.6, ymax=1.02]",
    ]
    for k, _, label, color in ENC:
        lines.append(rf"\addplot[{color}, thick, mark={MARK[k]}, mark size=1.6pt] table[x=m, y={k}_t4, col sep=comma] {{scale_data.csv}};")
        lines.append(rf"\addplot[{color}, thick, dashed, mark=none] table[x=m, y={k}_t8, col sep=comma] {{scale_data.csv}};")
    lines.append(r"\nextgroupplot[title={top-$k$ (nDCG@10)}, ylabel={nDCG@10 retained (\%)}, ymin=90, ymax=102, legend columns=1, legend style={at={(0.03,0.05)}, anchor=south west}]")
    for k, _, label, color in ENC:
        lines.append(rf"\addplot[{color}, thick, mark={MARK[k]}, mark size=1.6pt] table[x=m, y={k}_r4, col sep=comma] {{scale_data.csv}};")
        lines.append(rf"\addlegendentry{{{label}}}")
        lines.append(rf"\addplot[{color}, thick, dashed, mark={MARK[k]}, mark size=1.4pt, mark options={{solid}}, forget plot] table[x=m, y={k}_r3, col sep=comma] {{scale_data.csv}};")
    lines += [r"\end{groupplot}", r"\end{tikzpicture}", r"\end{document}", ""]
    (OUT / "scale_sweep.tex").write_text("\n".join(lines))
    print("wrote figures/scale_sweep.tex")


if __name__ == "__main__":
    main()
