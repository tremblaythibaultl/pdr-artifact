#!/usr/bin/env python3
"""Regenerate the three retrieval-side sweep figures from results/.

Writes figures/{quality,recall,agreement}_sweep.tex as standalone pgfplots
documents with their data embedded via filecontents, so each compiles on its
own and on Overleaf. Compile with `pdflatex <name>.tex` inside figures/.
Never run `latexmk -C` in figures/: it deletes the PDFs main.tex includes.

Layout: one row of two panels (SciFact, NFCorpus), one curve per encoder.
Solid curves are the encoders trained for low-bit readout, dashed the
conventional ones.
"""
from __future__ import annotations

import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = ROOT / "figures"

DATASETS = [("scifact", "SciFact"), ("nfcorpus", "NFCorpus")]

# key, results file stem, legend label, pgfplots style
ENCODERS = [
    ("arctic", "Snowflake_snowflake-arctic-embed-l-v2.0", "arctic-l-v2.0 (quant.-aware)",
     "red!80!black, thick, mark=*, mark size=1.5pt"),
    ("cohere", "embed-english-v3.0", "Cohere v3 (int8)",
     "orange!85!black, thick, mark=square*, mark size=1.4pt"),
    ("bge", "BAAI_bge-large-en-v1.5", "bge-large",
     "blue!70!black, thick, dashed, mark=triangle*, mark size=1.7pt, mark options={solid}"),
    ("mxbai", "mixedbread-ai_mxbai-embed-large-v1", "mxbai-large",
     "cyan!60!black, thick, dashed, mark=diamond*, mark size=1.7pt, mark options={solid}"),
    ("e5", "intfloat_e5-large-v2", "e5-large-v2",
     "green!55!black, thick, dashed, mark=pentagon*, mark size=1.5pt, mark options={solid}"),
    ("gte", "thenlper_gte-large", "gte-large",
     "violet, thick, dashed, mark=o, mark size=1.5pt, mark options={solid}"),
]

FIGS = {
    "quality_sweep": dict(
        metric=lambda r: 100 * float(r["ndcg_quantized"]) / float(r["ndcg_float"]),
        ylabel=r"nDCG@10 retained (\%)", ymin=60, ymax=104, ytick="60,70,...,100", xmin=2.5,
        what="fraction of floating-point nDCG@10 retained"),
    "recall_sweep": dict(
        metric=lambda r: 100 * float(r["recall_quantized"]) / float(r["recall_float"]),
        ylabel=r"Recall@10 retained (\%)", ymin=60, ymax=104, ytick="60,70,...,100", xmin=2.5,
        what="fraction of floating-point Recall@10 retained"),
    "agreement_sweep": dict(
        metric=lambda r: float(r["top1_agreement"]),
        ylabel="top-1 agreement with float", ymin=0, ymax=1.08, ytick="0,0.2,...,1", xmin=1.5,
        what="fraction of queries whose top-1 agrees with the floating-point ranking"),
}


def load(ds: str, stem: str, clip: float | None) -> dict[int, dict]:
    suffix = f"__clip{clip:g}" if clip is not None and clip < 100 else ""
    with (RES / f"{ds}__{stem}__k10{suffix}.csv").open() as f:
        return {int(r["bits"]): r for r in csv.DictReader(f)}


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--clip", type=float, default=None, help="read the __clip<p> sweep files (paper default: 99)")
    args = ap.parse_args()
    data = {(ds, key): load(ds, stem, args.clip) for ds, _ in DATASETS for key, stem, _, _ in ENCODERS}
    bits = sorted(next(iter(data.values())))
    for name, spec in FIGS.items():
        lines = [
            f"% {spec['what']} versus quantization bit-width, two corpora, six encoders.",
            f"% GENERATED by figures/gen_sweeps.py{' --clip ' + format(args.clip, 'g') if args.clip else ''} from results/<dataset>__<model>__k10{'__clip' + format(args.clip, 'g') if args.clip else ''}.csv.",
            "% Do not edit by hand; edit the generator and re-run it, then `pdflatex` this file.",
            "% Self-contained: data embedded via filecontents (compiles standalone and on Overleaf).",
            r"\documentclass[border=3pt]{standalone}",
            r"\usepackage{pgfplots}",
            r"\pgfplotsset{compat=1.18}",
            r"\usepgfplotslibrary{groupplots}",
            "",
        ]
        for ds, _ in DATASETS:
            lines.append(rf"\begin{{filecontents*}}[overwrite]{{{name}_{ds}.csv}}")
            lines.append("bits," + ",".join(k for k, *_ in ENCODERS))
            for b in bits:
                lines.append(f"{b}," + ",".join(f"{spec['metric'](data[(ds, k)][b]):.4f}" for k, *_ in ENCODERS))
            lines.append(r"\end{filecontents*}")
        lines += [
            "",
            r"\begin{document}",
            r"\begin{tikzpicture}",
            r"\begin{groupplot}[",
            r"    group style={group size=2 by 1, horizontal sep=1.3cm},",
            r"    width=7.4cm, height=4.0cm,",
            r"    xtick={2,3,4,5,6,7,8}, clip=true,",
            rf"    xmin={spec['xmin']}, xmax=8.5, ymin={spec['ymin']}, ymax={spec['ymax']}, ytick={{{spec['ytick']}}},",
            r"    tick label style={font=\small},",
            r"    label style={font=\small},",
            r"    title style={font=\small},",
            r"    grid=major, grid style={gray!20},",
            r"    scaled y ticks=false,",
            r"    xlabel={quantization bit-width $b$},",
            r"    legend cell align=left,",
            r"    legend style={font=\footnotesize, draw=black!40, fill=white, rounded corners=1pt,",
            r"                  /tikz/every even column/.append style={column sep=0.3cm}},",
            r"]",
        ]
        for i, (ds, title) in enumerate(DATASETS):
            opts = [f"title={{{title}}}"]
            if i == 0:
                opts.append(f"ylabel={{{spec['ylabel']}}}")
            else:
                opts.append("legend columns=3")
                opts.append("legend style={at={(-0.088,-0.34)}, anchor=north}")
            lines.append(r"\nextgroupplot[" + ", ".join(opts) + "]")
            for key, _, label, style in ENCODERS:
                lines.append(rf"\addplot[{style}] table[x=bits, y={key}, col sep=comma] {{{name}_{ds}.csv}};")
                if i == 1:
                    lines.append(rf"\addlegendentry{{{label}}}")
        lines += [r"\end{groupplot}", r"\end{tikzpicture}", r"\end{document}", ""]
        (OUT / f"{name}.tex").write_text("\n".join(lines))
        print(f"wrote figures/{name}.tex")


if __name__ == "__main__":
    main()
